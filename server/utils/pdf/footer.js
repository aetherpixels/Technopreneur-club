import QRCode from 'qrcode';
import { COLORS } from './helpers.js';

export const drawFooter = async (doc, width, pageHeight, startY, height, studentName, eventObj, certId, fonts) => {
  const qrSize = 40; // Shrink to fit in 56pt zone comfortably
  
  try {
    // Generate QR Code URL
    const verificationUrl = `${process.env.CLIENT_URL || 'http://localhost:5173'}/verify/${certId}`;
    const qrDataUrl = await QRCode.toDataURL(verificationUrl, { margin: 0, scale: 2 });
    const qrBuffer = Buffer.from(qrDataUrl.split(',')[1], 'base64');
    
    // Draw QR Code to the far right, vertically centered in the footer zone
    const qrX = width - 100;
    const qrY = startY + (height - qrSize) / 2 - 5;
    doc.image(qrBuffer, qrX, qrY, { width: qrSize, height: qrSize });
    
    // Verification Text Next to/Below QR Code
    doc.font(fonts.titleFont)
       .fontSize(6)
       .fillColor(COLORS.textSecondary)
       .text('Verify Certificate', qrX - 10, qrY + qrSize + 2, {
         width: qrSize + 20,
         align: 'center'
       });

  } catch (error) {
    console.error('QR Code Generation Error:', error);
  }

  // Draw the new full footer text horizontally centered
  const footerText = "This certificate has been digitally generated by Event-HuB – Institutional Activity Management System and is valid without a physical signature.\nThe authenticity of this certificate can be verified using the QR Code or Certificate ID.";
  
  doc.font(fonts.bodyFont)
     .fontSize(7)
     .fillColor(COLORS.textSecondary) // Grey color
     .text(footerText, 60, startY + 15, {
       width: width - 120,
       align: 'center',
       lineGap: 2
     });
     
  // Certificate ID
  doc.font(fonts.bodyFontBold)
     .fontSize(8)
     .fillColor(COLORS.navy)
     .text(`Certificate ID: ${certId}`, 60, startY + 35, {
       width: width - 120,
       align: 'center'
     });
};
